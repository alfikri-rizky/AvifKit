  /**
   * 64x48, 6 frames, 40 ms each, loops forever. A 16x16 square steps left to right, alternating red
   * and blue, over a white background — so consecutive frames differ, and frames after the first
   * are partial rectangles with a disposal method, which is what exercises compositing.
   */
  val MOVING_SQUARE: ByteArray by lazy { decodeHex(MOVING_SQUARE_HEX) }

  /**
   * 32x24, 3 frames, 50 ms each, set to play 3 times, and genuinely INTERLACED — row y carries
   * palette entry `(y + frameIndex) % 4`, so a decoder that skips de-interlacing gets almost every
   * row wrong instead of coincidentally matching. Hand-built (Pillow ignores its own `interlace`
   * save option), which is also why its LZW is literal-only.
   */
  val INTERLACED: ByteArray by lazy { decodeHex(INTERLACED_HEX) }

  /** 8x8, 2 frames, with a transparent palette index and "restore to background" disposal. */
  val TRANSPARENT: ByteArray by lazy { decodeHex(TRANSPARENT_HEX) }

  /** Position of the moving square's centre in [MOVING_SQUARE] / [INTERLACED] frame [index]. */
  fun squareCenterX(index: Int, frameCount: Int): Int = index * 48 / (frameCount - 1) + 8

  const val SQUARE_CENTER_Y = 18

  fun decodeHex(hex: String): ByteArray =
    ByteArray(hex.length / 2) { hex.substring(it * 2, it * 2 + 2).toInt(16).toByte() }

